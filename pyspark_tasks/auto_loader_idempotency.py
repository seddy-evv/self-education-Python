# ==========================================
# 4. Write to Delta Table using foreachBatch (UPSERT / MERGE)
# ==========================================
# Using foreachBatch ensures exact-once semantics and allows handling updates/upserts
# if duplicates span across micro-batches.
def upsert_to_delta(micro_batch_df, batch_id):
    # micro_batch_df is a standard, static Spark DataFrame for this batch
    # batch_id is a unique, monotonically increasing tracking integer

    target_table = DeltaTable.forName(spark, "default.silver_transactions")

    (target_table.alias("target")
     .merge(
        micro_batch_df.alias("source"),
        "target.record_id = source.record_id"
    )
     .whenMatchedUpdateAll()
     .whenNotMatchedInsertAll()
     .execute()
     )


