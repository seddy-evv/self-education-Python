# Start the streaming query with foreachBatch
query = (
    deduped_stream_df.writeStream
        .format("delta")
        .outputMode("update")  # Required when using dropDuplicatesWithinWatermark with MERGE/updates
        .option("checkpointLocation", checkpoint_path + "_chk")
        .foreachBatch(upsert_to_delta)
        .start()
)

