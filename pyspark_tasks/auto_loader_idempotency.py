# How to achieve idempotency with Databricks Autoloader and/or drop duplicates?

# 1. File-Level Ingestion Idempotency (Built-in via Auto Loader)
# Auto Loader handles file-level idempotency out of the box using its checkpoint location.

# How it works: Auto Loader maintains a state store inside your specified checkpointLocation. If your stream fails,
# restarts, or if you re-run the pipeline pointing to the same source directory, Auto Loader cross-references its
# state log and automatically skips already-ingested files.
# The Catch: Auto Loader guarantees that each file path is processed once. If a provider drops two separate files
# containing overlapping or duplicate records, Auto Loader will ingest both files, leading to duplicate records
# in your raw table.


# 2. Record-Level Idempotency (Handling Duplicate Rows)
# To achieve true end-to-end idempotency (ensuring duplicate or repeated records don't corrupt your dataset), you
# must handle deduplication downstream using one of two common patterns:

# Pattern A: Delta Lake MERGE INTO (Upserts via foreachBatch)
# If your source data contains unique business keys (e.g., transaction_id, order_id) and you want to prevent
# duplicates or handle updates, combine Auto Loader with a Delta MERGE statement inside foreachBatch.
# Normally, when you write a streaming query, Spark manages the micro-batches declaratively behind the scenes and hands
# them to a built-in sink (like Delta Lake or Kafka). However, standard streaming sinks only support simple appends and
# cannot run custom business code or transactional operations like an SQL MERGE INTO (upsert).
# - foreachBatch lets you define a custom Python (or Scala) function that gets executed on every single micro-batch
#   DataFrame generated by your stream.
# Why use foreachBatch?
# 1. Enables Upserts (MERGE INTO): Allows you to apply complex Delta Lake updates or deduplication logic
#    to every micro-batch.
# 2. Writing to External Sinks: Lets you push streaming data to relational databases (PostgreSQL, SQL Server),
#    NoSQL stores (Cosmos DB), or external APIs that do not have native Spark streaming connectors.
# 3. Multi-Sink Outputs: Allows you to write the exact same micro-batch DataFrame to multiple distinct locations
#    (e.g., both a Delta table and an external monitoring log).

from pyspark.sql import functions as F
from pyspark.sql.types import StructType, StructField, StringType, TimestampType, DoubleType





# ==========================================
# 1. Configuration & Schema Definition
# ==========================================
cloud_storage_path = "s3://your-bucket-name/path/to/json-source/"
checkpoint_path = "s3://your-bucket-name/checkpoints/json_autoloader/"
delta_table_path = "s3://your-bucket-name/delta/cleaned_data/"

# Define your schema explicitly for better performance and schema evolution handling
# Replace these fields with your actual JSON schema
schema = StructType([
    StructField("record_id", StringType(), True),
    StructField("event_timestamp", TimestampType(), True),
    StructField("data_value", DoubleType(), True),
    StructField("payload", StringType(), True)
])

# ==========================================
# 2. Ingest Data using Auto Loader (cloudFiles)
# ==========================================
raw_stream_df = (
    spark.readStream
        .format("cloudFiles")
        .option("cloudFiles.format", "json")
        .option("cloudFiles.inferColumnTypes", "true")  # Optional: Let Auto Loader infer types if schema isn't strict
        .option("cloudFiles.schemaLocation", checkpoint_path)  # Stores schema evolution metadata
        .schema(schema)
        .load(cloud_storage_path)
)

# Add metadata columns if needed (e.g., ingestion timestamp or source file name)
enriched_stream_df = raw_stream_df.withColumn(
    "_ingestion_time", F.current_timestamp()
).withColumn(
    "_source_file", F.col("_metadata.file_path")
)

# ==========================================
# 3. Deduplication in Streaming
# ==========================================
# Option A: Deduplication using watermark and dropDuplicatesWithinWatermark (Recommended for time-based deduplication)
# This requires a timestamp column and drops duplicates arriving within a specific time window.
deduped_stream_df = (
    enriched_stream_df
        .withWatermark("event_timestamp", "10 minutes")
        .dropDuplicatesWithinWatermark(["record_id"])
)

# Option B: If you need to deduplicate across all history using stateful streaming (requires RocksDB state store):
