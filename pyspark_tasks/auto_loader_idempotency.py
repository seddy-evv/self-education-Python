# Pattern B: Intra-Batch Deduplication (Window Functions)
# If you are doing standard appends but want to guarantee that identical records appearing within the same micro-batch
# are filtered out, you can use Spark SQL window functions:
from pyspark.sql.functions import col, row_number
from pyspark.sql.window import Window


def process_batch(micro_batch_df, batch_id):
    # Keep only the latest record per transaction_id if duplicates exist in the batch
    window_spec = Window.partitionBy("transaction_id").orderBy(col("ingest_timestamp").desc())

    clean_df = (
        micro_batch_df
            .withColumn("rn", row_number().over(window_spec))
            .filter(col("rn") == 1)
            .drop("rn")
    )

    clean_df.write.format("delta").mode("append").saveAsTable("default.clean_data")


